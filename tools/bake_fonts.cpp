// Bakes the GDI pixel fonts the renderer asks for into src/fonts.inc, so the web build
// (which has no GDI) draws exactly the same glyphs.
//   g++ -std=c++20 -O2 -o out/bake_fonts.exe tools/bake_fonts.cpp src/paint.cpp -lgdi32 -lgdiplus
//   out/bake_fonts.exe src/fonts.inc
#include "../src/paint.h"
#include <algorithm>
#include <cstdio>

struct Spec {
    const wchar_t* face;
    int px;
    bool bold;
};

// Keep in step with Renderer::init.
const Spec FONTS[] = {{L"Palatino Linotype", 13, false}, {L"Palatino Linotype", 17, false}, {L"Georgia", 46, true}};

int main(int argc, char** argv) {
    if (argc < 2) return 1;
    FILE* out = std::fopen(argv[1], "w");
    if (!out) return 1;
    paint::startup();
    std::fprintf(out, "// Generated by tools/bake_fonts.cpp from the Windows GDI fonts. Do not edit.\n");
    int index = 0;
    for (const Spec& s : FONTS) {
        FontAtlas a = paint::font(s.face, s.px, s.bold);
        int rows = 0;
        for (const Glyph& g : a.glyphs) rows = std::max(rows, g.y + g.h + 1);
        int words = a.image.w / 32;
        std::fprintf(out, "static const uint32_t FONT%d_BITS[] = {", index);
        for (int y = 0; y < rows; y++)
            for (int w = 0; w < words; w++) {
                uint32_t bits = 0;
                for (int b = 0; b < 32; b++)
                    if (a.image.rgba[size_t(y) * a.image.w + w * 32 + b] >> 24) bits |= 1u << b;
                std::fprintf(out, "%s0x%x,", (y * words + w) % 12 ? "" : "\n", bits);
            }
        std::fprintf(out, "\n};\n");
        std::fprintf(out, "static const BakedFont FONT%d = {%d, %d, %d, %d, %d, {", index, s.px, s.bold, a.lineHeight, a.image.w, rows);
        for (const Glyph& g : a.glyphs) std::fprintf(out, "{%d,%d,%d,%d,%d,%d},", g.x, g.y, g.w, g.h, g.offset, g.advance);
        std::fprintf(out, "}, FONT%d_BITS};\n", index);
        index++;
    }
    std::fprintf(out, "static const BakedFont* const BAKED_FONTS[] = {&FONT0, &FONT1, &FONT2};\n");
    std::fclose(out);
    paint::shutdown();
    return 0;
}
